-- TrueAlign Data: Oracle test data for SQL pushdown validation
-- Creates SRC_INVOICES (JDE-style source) and TGT_INVOICES (migrated target)
-- with one row per edge case. Safe to re-run: drops and recreates both tables.

SET DEFINE OFF
SET FEEDBACK OFF
SET HEADING ON
SET PAGESIZE 50
SET LINESIZE 120

CONNECT validator/"Test@1234#"@//localhost:1521/FREEPDB1

BEGIN EXECUTE IMMEDIATE 'DROP TABLE SRC_INVOICES PURGE'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE TGT_INVOICES PURGE'; EXCEPTION WHEN OTHERS THEN NULL; END;
/

WHENEVER SQLERROR EXIT FAILURE

-- Source: JD Edwards style. CHAR columns are space-padded, amounts are NUMBER, dates are DATE.
CREATE TABLE SRC_INVOICES (
  INVOICE_NO     CHAR(10),
  SUPPLIER_NAME  CHAR(30),
  AMOUNT         NUMBER(15,2),
  INVOICE_DATE   DATE,
  STATUS         VARCHAR2(10),
  REMARK         VARCHAR2(50)
);

-- Target: different column names, amounts stored as text, dates as TIMESTAMP.
CREATE TABLE TGT_INVOICES (
  INV_NUMBER   VARCHAR2(20),
  VENDOR_NAME  VARCHAR2(40),
  GROSS_AMT    VARCHAR2(20),
  INV_DATE     TIMESTAMP,
  INV_STATUS   VARCHAR2(10),
  COMMENTS     VARCHAR2(50)
);

-- INV001: identical except CHAR padding in key and name          -> MATCH
INSERT INTO SRC_INVOICES VALUES ('INV001', 'ACME CORP',        1500.00, DATE '2026-01-10', 'OPEN',   NULL);
INSERT INTO TGT_INVOICES VALUES ('INV001', 'ACME CORP',        '1500.00', TIMESTAMP '2026-01-10 00:00:00', 'OPEN',   NULL);

